  // AbortController : 비동기 작업의 취소를 지휘하고 중단 신호를 발생시킬 수 있는 권한을 가진 컨트롤러 객체
  // signal : 컨트롤러에 연결되어 취소 신호를 외부로 전달하고 현재 상태를 확인시켜 주는 AbortSignal 객체 속성
  // AbortSignal : 전달받은 중단 신호를 읽고(aborted), abort 이벤트를 수신할 수만 있는 수신 전용 신호 인터페이스
  // abort() : 연결된 비동기 작업에 즉시 취소 신호를 발송하고, 선택적으로 전달된 사유(reason)를 signal에 저장하는 메서드
  // aborted : 해당 작업이 컨트롤러를 통해 취소 요청을 받았는지 여부를 나타내는 읽기 전용 Boolean 플래그
  // reason : abort() 실행 시 인자로 전달받은 취소 사유(데이터, 문자열 또는 에러 객체)를 그대로 보관하는 속성
  //
  // [3. DOM 상속 계층 및 노드 인터페이스]
  // EventTarget : 이벤트를 등록, 해제, 발생시키는 기능을 가진 모든 브라우저 객체들의 최상위 부모 인터페이스
  // addEventListener() : 대상 객체에 특정 이벤트 발생 시 실행할 리스너 함수를 등록하는 메서드
  // removeEventListener() : 대상 객체에 기존 등록되어 있던 이벤트 리스너 함수를 찾아 제거하는 메서드
  // dispatchEvent() : 인위적으로 만든 이벤트 객체를 대상 요소에 강제로 발송하여 리스너를 실행시키는 메서드
  // Window : 브라우저 창 전체를 대표하며 모든 자바스크립트 전역 코드의 최상위 실행 컨텍스트가 되는 전역 객체
  // XMLHttpRequest : fetch 이전 시대에 서버와 비동기 HTTP 통신을 수행하기 위해 사용되던 구형 웹 API 객체
  // Node : DOM 트리 구조를 이루는 모든 구성 요소(요소, 텍스트, 주석 등)의 공통 부모가 되는 최상위 추상 인터페이스
  // parentNode : 현재 노드를 포함하고 있는 직속 상위 부모 노드 객체를 반환하는 읽기 전용 속성
  // childNodes : 현재 노드가 포함하고 있는 모든 직속 자식 노드들의 목록(NodeList 컬렉션)을 반환하는 속성
  // textContent : 현재 노드와 그 하위 모든 자손 노드들이 포함하고 있는 순수 텍스트 콘텐츠 전체를 읽거나 쓰는 속성
  // CharacterData : Text, Comment 등 순수 문자열 데이터를 다루는 노드들의 공통 추상 기본 인터페이스
  // Text : HTML 태그 내부 또는 태그 사이에 실제로 존재하는 순수 텍스트 데이터를 나타내는 노드 객체
  // Comment : HTML 소스 마크업 상의 주석(<!-- -->) 내용을 데이터로 나타내는 노드 객체
  // Document : 브라우저에 로드된 HTML/XML 웹 페이지 문서 전체를 대표하는 DOM 트리의 메인 진입점 인터페이스
  // querySelector() : 전달된 CSS 선택자와 일치하는 문서 내 첫 번째 Element 요소를 탐색해 반환하는 메서드
  // createElement() : 인자로 전달된 태그 이름에 해당하는 새로운 HTML 요소(Element) 노드를 메모리에 생성하는 메서드
  // Element : 모든 HTML/XML 태그 요소들의 공통 인터페이스로 태그 속성 및 식별자를 제어하는 기능 제공
  // id : HTML 문서 내에서 해당 요소를 고유하게 식별하기 위해 부여하는 문자열 식별자 속성
  // classList : 요소의 class 속성값들을 개별 클래스 단위로 쉽게 추가, 제거, 토글할 수 있게 해주는 실시간 컬렉션 속성
  // getAttribute() : 요소에 명시된 특정 HTML 속성의 값을 문자열 형태로 직접 읽어오는 메서드
  // HTMLElement : 모든 'HTML 태그'에만 한정되어 적용되는 표준 인터페이스 (스타일, 렌더링 속성 제공)
  // style : 요소의 인라인 CSS 스타일 속성들을 자바스크립트 객체 형태로 읽거나 조작할 수 있게 해주는 속성
  // dataset : HTML5 data-* 커스텀 데이터 속성들을 카멜케이스 객체 형태로 쉽게 다룰 수 있게 해주는 속성
  // hidden : 화면에 해당 HTML 요소를 노출시키지 않고 숨김 처리할지 여부를 제어하는 Boolean 속성
  // HTMLInputElement : <input> 태그 요소를 자바스크립트에서 다루기 위해 정의된 특화 인터페이스
  // value : <input>, <textarea> 등 폼 입력 요소에 현재 입력되어 있는 문자열 값을 취득하거나 변경하는 속성
  // checked : 체크박스나 라디오 버튼 요소가 현재 선택되어 있는 상태인지를 나타내는 Boolean 속성
  // HTMLDivElement : <div> 태그 요소를 자바스크립트에서 다루기 위해 정의된 전용 인터페이스
  //
  // [4. 이벤트 객체 계층 및 이벤트 전파]
  // Event : DOM에서 발생하는 모든 사건(클릭, 로드 등)의 상태와 기본 기능을 정의하는 최상위 이벤트 인터페이스
  // type : 현재 발생한 해당 이벤트의 고유 식별 명칭(예: "click", "keydown")을 나타내는 읽기 전용 속성
  // target : 이벤트 전파 과정과 무관하게 이벤트를 실제로 발생시킨 최초의 원인 객체를 가리키는 속성
  // currentTarget : 이벤트 전파 과정 중 현재 이벤트 리스너 함수가 바인딩되어 실행 중인 대상 요소를 가리키는 속성
  // bubbles : 해당 이벤트가 발생 대상에서부터 상위 부모 노드로 역방향 전파(버블링)되는 종류인지 나타내는 Boolean 속성
  // preventDefault() : 브라우저가 특정 이벤트에 대해 기본적으로 수행하는 고유 동작(링크 이동, 폼 전송 등)을 취소하는 메서드
  // CustomEvent : 개발자가 필요한 임의의 데이터(detail 속성)를 담아 인위적으로 정의하고 발송할 수 있는 사용자 정의 이벤트
  // ProgressEvent : 데이터 전송, 파일 다운로드 등 비동기 요청의 진행률과 상태(loaded, total)를 모니터링하는 이벤트 객체
  // UIEvent : 사용자 화면 상호작용(뷰포트, 디스플레이)과 결부되어 발생하는 모든 이벤트 객체의 부모 인터페이스
  // view : 이벤트가 발생한 윈도우 환경(추상화된 WindowProxy)의 참조 정보를 담고 있는 읽기 전용 속성
  // detail : 이벤트 유형에 따라 제공되는 추가 상세 정보(예: 마우스 클릭 시 연속 클릭 횟수)를 나타내는 속성
  // KeyboardEvent : 사용자가 키보드의 키를 누르거나 뗄 때 발생하는 물리적 입력 정보를 다루는 이벤트 객체
  // key : 사용자가 누른 키보드 키의 실제 문자 값(예: "Enter", "a", "Escape")을 나타내는 속성
  // code : 키보드 상에서 눌린 키의 물리적 하드웨어 위치 코드(예: "KeyA", "Space")를 나타내는 속성
  // repeat : 사용자가 키를 떼지 않고 길게 누르고 있어 키 입력이 반복 발생 중인지 나타내는 Boolean 속성
  // MouseEvent : 사용자가 마우스나 트랙패드를 조작할 때 발생하는 물리적 화면 좌표 및 버튼 상호작용 이벤트 객체
  // clientX : 이벤트가 일어난 시점의 브라우저 뷰포트(표시 영역) 기준 가로 X 좌표를 나타내는 속성
  // button : 마우스 이벤트 발생 시 어떤 마우스 버튼(0: 좌클릭, 1: 휠클릭, 2: 우클릭)이 눌렸는지 식별하는 속성
  // ctrlKey : 마우스나 키보드 이벤트 발생 당시 Ctrl(컨트롤) 키가 함께 눌려 있던 상태였는지 나타내는 Boolean 속성
  // PointerEvent : 마우스, 터치스크린, 스타일러스 펜 등 모든 화면 입력 도구를 단일 규격으로 통합 추상화한 포인터 이벤트
  // pointerType : 이벤트를 촉발한 물리적 입력 장치의 세부 유형("mouse", "pen", "touch")을 나타내는 속성
  // pressure : 스타일러스 펜이나 터치 화면에서 사용자가 디스플레이를 누르는 물리적 압력의 강도(0~1 범위) 속성
  // WheelEvent : 사용자가 마우스 휠을 돌리거나 터치패드로 스크롤 조작을 할 때 발생하는 전용 물리 이벤트 객체
  // deltaY : 마우스 휠이나 제스처로 인해 화면 스크롤이 수직 방향(Y축)으로 이동한 실제 픽셀 거리와 방향 속성
  // 캡처링 (Capturing) : 이벤트가 발생한 대상 요소를 찾기 위해 최상위 Window에서 하위 자식 노드로 내려가는 하향식 전파 단계
  // 버블링 (Bubbling) : 이벤트가 발생한 대상(target) 요소에서 상위 부모 노드들을 거쳐 최상위 Window로 거슬러 올라가는 상향식 전파 단계
  //
  // [5. 브라우저 탐지, 프로퍼티 제어 및 보안 환경]
  // Object.defineProperty() : 객체에 새로운 프로퍼티를 직접 정의하거나 기존 프로퍼티의 동작(getter/setter, 설정 가능성 등)을 수정하는 메서드
  // getter (get()) : 객체의 특정 프로퍼티 값을 읽으려고 접근하는 순간 브라우저 내부에서 자동으로 실행되는 가로채기 함수
  // setter (set()) : 객체의 특정 프로퍼티에 새로운 값을 대입하려고 할 때 브라우저 내부에서 자동으로 실행되는 가로채기 함수
  // Object.getOwnPropertyDescriptor() : 특정 객체 자신이 직접 소유한 프로퍼티의 속성 서술자(getter, setter, configurable 등)를 조회하는 메서드
  // UA 스니핑 (User-Agent Sniffing) : navigator.userAgent 문자열을 파싱하여 특정 브라우저를 식별하려는 안티패턴 기법
  // 기능 탐지 (Feature Detection) : 브라우저 이름을 판별하지 않고, 특정 기능이나 API가 전역 환경에 실제로 존재하는지 직접 확인하는 권장 패턴
  // "key" in object : 프로토타입 체인을 포함하여 대상 객체 안에 특정 프로퍼티나 API 이름이 존재하는지 판별하는 안전한 연산자
  // typeof : 대상 식별자의 원시 데이터 타입 또는 전역 객체 존재 여부를 참조 에러(ReferenceError) 없이 판별하는 키워드
  // window.someAPI : 전역 객체에 특정 API가 선언되어 있는지 접근하는 방식으로, 존재하지 않으면 undefined를 반환함
  // isSecureContext : 현재 웹 페이지가 암호화된 통신(HTTPS 또는 localhost) 환경에서 안전하게 실행 중인지를 나타내는 Boolean 속성
  // window.isSecureContext : Window 객체 상에서 현재 브라우저 탭이 중간자 공격으로부터 안전한 보안 컨텍스트인지 판별하는 읽기 전용 속성
  // crypto : 브라우저가 기본 내장하고 있는 표준 웹 암호화(Web Crypto) 기능들이 모여있는 최상위 전역 객체
  // subtle : 해시, 디지털 서명, 대칭/비대칭 암복호화 등 하위 레벨의 복잡한 암호 연산을 처리하는 실제 메서드들이 담긴 속성
  // crypto.subtle : Web Crypto API의 하위 레벨 암호화 인터페이스로, 반드시 보안 컨텍스트(isSecureContext가 true)에서만 접근 가능
  //
  // [6. 표준 호환성 및 명세 상태 표기]
  // Baseline : Chrome, Safari, Firefox, Edge 등 4대 메이저 브라우저에 모두 구현 완료되어 안전하게 쓸 수 있는 기준점
  // Widely available : Baseline 도달 후 30개월 이상 경과하여 거의 모든 사용자의 구버전 환경까지 완벽히 포용 가능한 안정 상태
  // Newly available : 최근 4대 브라우저에 구현이 완료된 초기 단계로, 서비스 대상 사용자의 브라우저 점유율을 검토해야 하는 상태
  // Experimental : 웹 표준 명세나 세부 동작이 향후 수정될 수 있어 상용 프로덕션 환경 도입 시 주의가 필요한 실험적 API
  // Deprecated : 웹 표준에서 공식 폐기 예정이므로 유지보수를 위해 신규 프로젝트 코드에서는 절대 사용하지 말아야 할 기능
  // Non-standard : W3C/WHATWG 공식 웹 표준 명세가 아니며 특정 브라우저 엔진에서만 독점적/임의로 구현된 비표준 기능
  //
  // [7. Web API 7대 설계 패턴 및 시스템 리소스 관리]
  // 생성자 (Constructor) : new 키워드를 통해 새로운 인스턴스 객체를 메모리에 초기화하고 생성하는 함수
  // 옵션 딕셔너리 : 생성자나 메서드의 마지막 인자로 전달하여 부가 설정을 지정하는 키-값 형태의 자바스크립트 객체
  // 프로미스 반환 (Promise-returning) : 비동기 작업 완료 시 결과를 반환하는 패턴으로, async/await 문법과 결합하여 비동기 흐름 제어
  // 콜백 (Callback) : 특정 작업이 완료되거나 특정 이벤트/변화가 감지되었을 때 브라우저 엔진에 의해 호출되도록 전달하는 함수
  // Observer : 특정 대상(DOM 변화, 화면 교차, 크기 변경 등)의 상태 변화를 백그라운드에서 비동기로 관측하는 웹 감시자 객체
  // observe() : 관측 대상이 되는 특정 DOM 요소나 리소스를 지정하여 Observer 감시 장치를 가동시키는 메서드
  // disconnect() : Observer가 현재 감시 중인 모든 대상 요소들의 관측을 즉시 중단하고 감시 장치를 완전히 해제하는 메서드
  // Mutation : DOM 트리의 내부 구조(자식 노드 추가/삭제, 속성 변경, 텍스트 수정 등)에 물리적인 변동이 일어나는 현상
  // 컨트롤러 (Controller) : 비동기 작업이나 제어 대상을 중단, 조작, 취소할 수 있는 실질적인 제어 권한을 쥐고 있는 객체
  // 신호 분리 (Signal Separation) : 명령을 내리는 권한(Controller)과 명령 상태를 통보받아 읽기만 하는 권한(Signal)을 독립 분리하는 설계
  // 데이터 스트림 (Data Stream) : 대용량 데이터를 한 번에 메모리에 올리지 않고 작은 조각(청크) 단위로 연속하여 순차 처리하는 데이터 흐름
  // 일회성 소비 (Single-use Consumption) : 데이터 스트림이나 응답 본문(body)을 한 번 읽으면 내부가 잠겨 재사용이 영구 불가능해지는 설계
  // 핸들 수명 관리 (Handle Lifecycle) : 브라우저 내부 네이티브 리소스를 점유한 식별자를 생성한 뒤 누수를 막기 위해 명시적으로 해제하는 설계
  // URL : 웹 주소를 표현하고 파싱하며 관련 유틸리티 정적 메서드를 제공하는 최상위 웹 URL 객체
  // URL.createObjectURL() : 전달받은 파일(File)이나 바이너리 데이터(Blob)를 가리키는 고유한 가상 메모리 URL 문자열을 생성하는 정적 메서드
  // URL.revokeObjectURL() : createObjectURL로 생성했던 임시 가상 메모리 식별자를 명시적으로 폐기하여 브라우저 메모리 누수를 방지하는 정적 메서드
