  // 프로토타입체이닝 : 객체에 찾는 속성이 없을 때 숨겨진 링크(__proto__)를 타고 최상위 Object까지 거슬러 올라가며 탐색하는 메커니즘
  // 클래스 : 프로토타입 기반 상속 구조 위에 객체지향 문법처럼 보이도록 씌워둔 편의용 문법적 껍데기(Syntactic Sugar)
  // 차이점 : 전통적 클래스는 설계도를 메모리에 복사(Copy)하지만, JS는 복사 없이 부모 프로토타입 객체를 참조 링크로 연결해 빌려 씀
